"""Regenerate src/mcpiranha/rules/known_packages.py (MCP-XS-003's typosquat targets) from the
registry and download counts that build_targets.py cached, and measure the result.

Usage: uv run python calibration/update_known_packages.py [--npm 300] [--pypi 150] [--check]

The most-downloaded stdio packages in the official registry are what a typosquatter would
imitate. --check only measures: how many registry packages the current list would flag (nearly
all registry packages are legitimate, so every hit is a likely false positive to review).
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

from mcpiranha.rules.builtin.typosquat import PYPI_FOLD, closest

HERE = Path(__file__).parent
OUT = HERE.parent / "src" / "mcpiranha" / "rules" / "known_packages.py"
HEADER = '''"""Widely used MCP server packages: the names typosquatters imitate (MCP-XS-003).

Generated by calibration/update_known_packages.py from the official MCP registry and
last-month download counts ({date}), plus curated well-known packages: {npm} npm and
{pypi} PyPI names.
Being on this list says nothing about a package's safety; it only means a near-miss of the
name is suspicious. Regenerate rather than edit by hand.
"""

'''


# Well-known packages that aren't (all) in the registry, e.g. the reference servers from
# github.com/modelcontextprotocol/servers. Always included.
CURATED_NPM = frozenset({
    "@azure/mcp",
    "@cloudflare/mcp-server-cloudflare",
    "@modelcontextprotocol/inspector",
    "@modelcontextprotocol/server-brave-search",
    "@modelcontextprotocol/server-everything",
    "@modelcontextprotocol/server-filesystem",
    "@modelcontextprotocol/server-github",
    "@modelcontextprotocol/server-gitlab",
    "@modelcontextprotocol/server-google-maps",
    "@modelcontextprotocol/server-memory",
    "@modelcontextprotocol/server-postgres",
    "@modelcontextprotocol/server-puppeteer",
    "@modelcontextprotocol/server-redis",
    "@modelcontextprotocol/server-sequential-thinking",
    "@modelcontextprotocol/server-slack",
    "@notionhq/notion-mcp-server",
    "@playwright/mcp",
    "@sentry/mcp-server",
    "@stripe/mcp",
    "@supabase/mcp-server-supabase",
    "@upstash/context7-mcp",
    "figma-developer-mcp",
    "firecrawl-mcp",
    "mcp-remote",
})  # fmt: skip
CURATED_PYPI = frozenset({
    "fastmcp",
    "mcp",
    "mcp-server-fetch",
    "mcp-server-git",
    "mcp-server-sqlite",
    "mcp-server-time",
})  # fmt: skip


def load() -> tuple[dict[str, int], dict[str, int]]:
    counts = json.loads((HERE / ".cache" / "downloads.json").read_text(encoding="utf-8"))
    npm = {k[4:]: v or 0 for k, v in counts.items() if k.startswith("npm:")}
    pypi = {k[5:]: v or 0 for k, v in counts.items() if k.startswith("pypi:")}
    return npm, pypi


def top(counts: dict[str, int], n: int, minimum: int = 1000) -> list[str]:
    return [name for name, c in sorted(counts.items(), key=lambda x: -x[1])[:n] if c >= minimum]


def check(npm: dict[str, int], pypi: dict[str, int], known_npm: frozenset[str],
          known_pypi: frozenset[str]) -> None:  # fmt: skip
    hits: list[tuple[str, str, int, int, str]] = []
    for name in npm:
        if (match := closest(name, known_npm)) is not None:
            hits.append(("npm", name, npm[name], npm.get(match[0], 0), match[0]))
    for name in pypi:
        folded = name.lower().translate(PYPI_FOLD)
        if (match := closest(folded, known_pypi)) is not None:
            hits.append(("pypi", name, pypi[name], pypi.get(match[0], 0), match[0]))
    print(f"registry packages flagged: {len(hits)} of {len(npm) + len(pypi)}")
    print("by registry:", dict(Counter(h[0] for h in hits)))
    for registry, name, downloads, target_downloads, target in sorted(hits, key=lambda h: -h[2])[
        :40
    ]:
        print(f"  {registry:4} {name:55} {downloads:>9}/mo  ~ {target} ({target_downloads}/mo)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--npm", type=int, default=300)
    parser.add_argument("--pypi", type=int, default=150)
    parser.add_argument("--check", action="store_true", help="measure the current list only")
    options = parser.parse_args()
    npm, pypi = load()

    if options.check:
        from mcpiranha.rules.known_packages import KNOWN_NPM, KNOWN_PYPI

        check(npm, pypi, KNOWN_NPM, KNOWN_PYPI)
        return

    import datetime

    names_npm = sorted(set(top(npm, options.npm)) | CURATED_NPM)
    names_pypi = sorted(set(top(pypi, options.pypi, minimum=100)) | CURATED_PYPI)
    body = HEADER.format(date=datetime.date.today().isoformat(), npm=len(names_npm),
                         pypi=len(names_pypi))  # fmt: skip
    for var, names in (("KNOWN_NPM", names_npm), ("KNOWN_PYPI", names_pypi)):
        body += f"{var}: frozenset[str] = frozenset({{\n"
        body += "".join(f"    {json.dumps(n)},\n" for n in sorted(names))
        body += "})  # fmt: skip\n\n"
    OUT.write_text(body.rstrip() + "\n", encoding="utf-8")
    print(f"wrote {len(names_npm)} npm and {len(names_pypi)} PyPI names to {OUT}")
    check(npm, pypi, frozenset(names_npm), frozenset(names_pypi))


if __name__ == "__main__":
    main()
